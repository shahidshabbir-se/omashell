const assert = require('node:assert/strict')
const m = require('./Model.js')

assert.equal(m.decodeEntities('Tom &amp; Jerry &lt;3'), 'Tom & Jerry <3')
assert.equal(m.decodeEntities('&amp;quot;quoted&amp;quot;'), '"quoted"')
assert.equal(m.oneLine('Tom &amp; Jerry'), 'Tom & Jerry')
assert.equal(m.oneLine('<b>bold</b>  text'), 'bold text')
assert.equal(m.oneLine('<script>alert(1)</script>safe'), '<script>alert(1)</script>safe')
assert.match(m.renderBody('<b>hi</b>'), /^<b>hi<\/b>$/)
assert.match(m.renderBody('a\nb'), /^a<br\/>b$/)
assert.match(m.renderBody('<script>x</script>'), /&lt;script&gt;/)
assert.match(m.renderBody('<a href="https://example.com/x">site</a>'), /href="https:\/\/example.com\/x"/)
assert.equal(m.renderBody('<a href="javascript:alert(1)">bad</a>'), 'bad')
assert.match(m.renderBody('see https://example.com/a'), /<a href="https:\/\/example.com\/a">/)
assert.equal(m.safeHttpUrl('javascript:alert(1)'), '')
assert.equal(m.safeHttpUrl('https://example.com/path'), 'https://example.com/path')
assert.equal(m.safeHttpUrl('https://user@example.com/'), '')
assert.equal(m.safeHttpUrl('https://example.com:99999/'), '')
assert.equal(m.safeHttpUrl('http://example.com:8080/x?y=1'), 'http://example.com:8080/x?y=1')

const row = m.snapshot({
  id: 7, app: 'Spotify', appIcon: 'spotify', summary: 'Now playing', body: '<b>Song</b>',
  urgency: 2, timeout: 12000,
  actions: [{ id: 'open', text: 'Open' }, { id: '', text: 'broken' }]
}, 'k1', 1000)
assert.equal(row.app, 'Spotify')
assert.equal(row.urgency, 2)
assert.equal(row.timeout, 12000)
assert.deepEqual(row.actions, [{ id: 'open', text: 'Open' }])
assert.equal(row.time, 1000)
assert.equal(m.snapshot({}, 5).urgency, 1)
assert.equal(m.snapshot(null, 6).summary, '')
assert.equal(m.safeImage('/tmp/shot.png'), 'file:///tmp/shot.png')
assert.equal(m.safeImage('/proc/self/environ'), '')
assert.equal(m.safeImage('/run/user/1000/omasnap/shot.png'), 'file:///run/user/1000/omasnap/shot.png')
assert.equal(m.safeImage('/run/secrets/token.png'), '')
assert.equal(m.safeImage('/tmp/../secret'), '')
assert.deepEqual(m.codes('Verification code', 'Your code is 482913'), ['482913'])
assert.deepEqual(m.codes('Build complete', '482913'), [])
assert.deepEqual(m.execActions([{label: 'Open', argv: ['xdg-open', 'file:///tmp/a.png']}]), [
  {label: 'Open', argv: ['xdg-open', 'file:///tmp/a.png']}
])
assert.deepEqual(m.execActions([{label: 'Bad', argv: ['-rf', '/']}]), [])
assert.deepEqual(m.execArgv('["omasnap","--file","/tmp/a.png"]'), ['omasnap', '--file', '/tmp/a.png'])
assert.deepEqual(m.execArgv(['bad\u0000arg']), [])

assert.equal(m.durationFor(2, 0), 0)
assert.equal(m.durationFor(0, 0), m.LOW_DURATION)
assert.equal(m.durationFor(1, 0), m.NORMAL_DURATION)
assert.equal(m.durationFor(1, 60000), m.MAX_DURATION)
assert.equal(m.durationFor(0, 12000), 12000)

assert.equal(m.isEphemeral({app: 'notify-send'}), true)
assert.equal(m.isEphemeral({app: 'Slack'}), false)
assert.equal(m.isEphemeral({app: 'Slack', transient: true}), true)
assert.equal(m.quietReason({app: 'Slack'}, false), '')
assert.equal(m.quietReason({app: 'Slack'}, true), 'silenced')
assert.equal(m.quietReason({app: 'notify-send', urgency: 2}, true), '')
assert.equal(m.quietReason({app: 'notify-send', urgency: 1}, true), 'silenced')

assert.equal(m.ago(999700, 1000000), '')
assert.equal(m.ago(1000000 - 600 * 1000, 1000000), '10m')
assert.equal(m.ago(1000000 - 90000 * 1000, 1000000), 'yesterday')
assert.match(m.ago(1000000 - 5000 * 1000, 1000000), /^\d\d:\d\d$/)
assert.equal(m.ago(0, 1000000), '')
const layout = m.panelLayout([
  { key: 'a1', app: 'Slack' }, { key: 'a2', app: 'Slack' }, { key: 'b1', app: 'Mail' }
], false, {a1: 100, a2: 50, b1: 80})
assert.equal(layout.placements.a1.y, 0)
assert.equal(layout.placements.a1.opacity, 1)
assert.equal(layout.placements.a2.y, m.PEEK)
assert.equal(layout.placements.a2.opacity, 0.85)
assert.equal(layout.placements.a2.height, 100)
assert.ok(layout.placements.b1.y >= 100)
const open = m.panelLayout([
  { key: 'a1', app: 'Slack' }, { key: 'a2', app: 'Slack' }
], true, {a1: 100, a2: 50})
assert.equal(open.placements.a2.y, 106)
assert.equal(open.placements.a2.scale, 1)
assert.equal(open.height, 156)
const oneOpen = m.panelLayout([
  { key: 'a1', app: 'Slack' }, { key: 'a2', app: 'Slack' }, { key: 'b1', app: 'Mail' }
], true, {a1: 100, a2: 50, b1: 80}, {openGroup: 'app:slack'})
assert.equal(oneOpen.placements.a2.y, 106)
assert.equal(oneOpen.placements.b1.y, 168)
assert.equal(oneOpen.placements.b1.scale, 1)
assert.equal(m.slug('Google Chrome'), 'google-chrome')
assert.equal(m.groupKey({app: 'Slack', key: 'a'}), 'app:slack')
assert.equal(m.groupKey({app: 'notify-send', key: 'b'}), 'toast:b')

const state = m.parseState(m.serialise({dnd: true, history: [m.entry(row, 'closed', 2000)]}))
assert.equal(state.dnd, true)
assert.equal(state.history.length, 1)
assert.equal(state.history[0].summary, 'Now playing')
assert.deepEqual(m.parseState('nonsense'), {dnd: false, history: []})
assert.deepEqual(m.parseState('{"history":"bad"}'), {dnd: false, history: []})
assert.deepEqual(m.parseState(JSON.stringify({history: [{key: '', summary: 'x'}]})).history, [])
assert.equal(m.cap([1, 2, 3], 2).length, 2)
assert.deepEqual(m.actions({0: {id: 'a', text: 'A'}, length: 1}), [{id: 'a', text: 'A'}])
