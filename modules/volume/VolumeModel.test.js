const assert = require('node:assert/strict')
const model = require('./VolumeModel.js')
assert.equal(model.iconFor(0, false), '')
assert.equal(model.iconFor(33, false), '')
assert.equal(model.iconFor(34, false), '')
assert.equal(model.iconFor(67, false), '')
assert.equal(model.iconFor(90, true), '')
assert.deepEqual(model.state(1.5, false), { percent: 100, progress: 1, icon: '', label: '100%' })
assert.equal(model.state(-1, false).percent, 0)
const a = {}, b = {}
let previous = model.observe(null, a, 0.5, false)
assert.equal(previous.changed, false)
previous = model.observe(previous, a, 0.6, false)
assert.equal(previous.changed, true)
previous = model.observe(previous, a, 0.6, true)
assert.equal(previous.changed, true)
previous = model.observe(previous, b, 0.2, false)
assert.equal(previous.changed, false)
previous = model.observe(previous, null, 0, false)
assert.equal(previous.changed, false)
assert.equal(model.observe(previous, b, 0.2, false).changed, false)
console.log('Volume OSD model tests passed')
